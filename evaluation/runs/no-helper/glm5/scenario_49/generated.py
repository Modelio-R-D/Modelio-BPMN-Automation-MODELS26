# ComputerRepairProcess.py
#
# Description:
#   BPMN process diagram for Computer Repair workflow.
#   3 lanes: Customer, CRS (Customer Service Representative), Technician
#
# Workflow:
#   1. Customer brings defective computer
#   2. CRS checks defect and hands out cost calculation
#   3. Customer decides: accept costs or take computer home
#   4. If accepted: parallel hardware and software repair activities
#   5. Test system functionality after repairs complete
#   6. If error detected: loop back to repair activities
#   7. If no error: computer repaired successfully
#
# Applicable on: Package
#
# Version: 1.0
#

