SCRIPT_VERSION = "v1.0"
EXECUTION_ID = str(int(time.time() * 1000) % 100000)

WAIT_TIME_MS = 50
MAX_ATTEMPTS = 3

SPACING = 150
START_X = 80
TASK_WIDTH = 120
TASK_HEIGHT = 60

