# Description:
#   BPMN process diagram for Parental Leave Management.
#   Supports planning, taking, and extending maternity/paternity leave.
#   3 lanes: Parent, HR Department, Social Security
#
# Workflow:
#   1. Fetch information about potential leave models
#   2. Let parent select preferred model
#   3. Collect relevant personal and employment information
#   4. Gather information from companies
#   5. Notify Social Security and Company in time
#   6. At end of period, let parent decide about extension
#
# Applicable on: Package
#
# Version: 1.0
#

