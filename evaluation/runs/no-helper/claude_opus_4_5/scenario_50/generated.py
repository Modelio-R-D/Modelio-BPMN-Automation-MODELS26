# Description:
#   BPMN process diagram for Claim Handling workflow.
#   2 lanes: Claims Officer, Senior Claims Officer
#
#   Flow:
#   1. Claim is registered (start)
#   2. Claims Officer examines the claim
#   3. Claims Officer writes settlement recommendation
#   4. Senior Claims Officer checks the recommendation
#   5. Decision: OK or Not OK
#      - Not OK: Goes back to Claims Officer to rewrite recommendation
#      - OK: Process proceeds to completion
