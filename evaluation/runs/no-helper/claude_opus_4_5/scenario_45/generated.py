#
# OnlineShopOrdering.py
#
# Description:
#   BPMN process diagram for Online Shop Ordering workflow.
#   3 lanes: Customer, E-Shop System, Bank
#
# Process Flow:
#   1. Customer logs in, system checks credentials
#   2. If successful: select products loop (select -> add to cart -> save -> check)
#   3. Finish order triggers parallel: payment and shipment preparation
#   4. Payment: enter payment data, wait for bank confirmation
#   5. While waiting: enter shipping address (optionally billing address)
#   6. When both complete: system finishes order
#
# Applicable on: Package
# Version: 1.0
#

